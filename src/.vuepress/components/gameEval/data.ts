import { h } from "vue";

// 游戏评价接口
export interface GameEvaluation {
  gameName: string;
  gameNameEn: string;
  gameCategory: string[];
  gameTime: string;
  rating: number;
  key: string;
}

// 表格列名
export const gameEvalColumns = [
  {
    title: "游戏名称",
    dataIndex: "gameName",
    key: "gameName",
    width: 250,
  },
  {
    title: "游戏分类",
    dataIndex: "gameCategory",
    key: "gameCategory",
    width: 200,
    render: (_, record) => {
      return record.gameCategory.map((category, index) =>
        h(
          "span",
          {
            key: index,
            class: "category-tag",
          },
          category,
        ),
      );
    },
  },
  {
    title: "游戏时间",
    dataIndex: "gameTime",
    key: "gameTime",
    width: 150,
    sorter: {
      compare: (a, b) => a.gameTime - b.gameTime,
      multiple: 1,
    },
  },
  {
    title: "好评率",
    dataIndex: "rating",
    key: "rating",
    width: 150,
    sorter: {
      compare: (a, b) => a.rating - b.rating,
      multiple: 2,
    },
    render: (_, record) => {
      return h(
        "span",
        {
          class: "score-tag",
          style: {
            color:
              record.rating >= 90
                ? "#52c41a"
                : record.rating >= 80
                  ? "#1890ff"
                  : record.rating >= 70
                    ? "#faad14"
                    : "#f5222d",
          },
        },
        record.rating,
      );
    },
  },
];

